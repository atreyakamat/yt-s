// Lists every topic already used (so new scripts never repeat one) and the next free reel ids.
//   node tools/topics.mjs          -> writes ../how-things-work/TOPICS.md, prints the next free id
//   node tools/topics.mjs 50       -> also prints the next 50 free ids
import fs from "node:fs";
import path from "node:path";
import { parse } from "./miniyaml.mjs";
import { batchDir, contentDir, idNum, validateAll } from "./validate.mjs";

const want = Number(process.argv[2] ?? 0);
const { reels } = validateAll(parse);
const used = new Set(reels.map((r) => idNum(r.id)));
const max = Math.max(...used);
const next = [];
for (let n = 1; next.length < Math.max(1, want); n++) if (!used.has(n)) next.push(n);

const bySeries = {};
for (const r of reels) (bySeries[r.series] ??= []).push(r);
const lines = [
  "# Topics already used",
  "",
  `${reels.length} reels (vid-1 to vid-${max}). A new script's \`topic:\` must not repeat any of these, or be the same`,
  "object under another name. Generated by `npm run topics`; don't edit by hand.",
  "",
  ...Object.entries(bySeries).flatMap(([s, rs]) => [
    `## ${s} (${rs.length})`,
    "",
    rs
      .map((r) => String(r.topic ?? r.title))
      .sort((a, b) => a.localeCompare(b))
      .join(" · "),
    "",
  ]),
];
fs.writeFileSync(path.join(contentDir, "TOPICS.md"), lines.join("\n"));
console.log(`Wrote how-things-work/TOPICS.md (${reels.length} topics).`);
console.log(`Next free id: vid-${next[0]} (folder how-things-work/${batchDir(next[0])}/)`);
if (want > 1) console.log(`Next ${want} free ids: ${next.map((n) => `vid-${n}`).join(", ")}`);
