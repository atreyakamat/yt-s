// Writes how-things-work/INDEX.md: every reel in posting order, grouped by batch folder. No dependencies.
//   node tools/index.mjs
import fs from "node:fs";
import path from "node:path";
import { parse } from "./miniyaml.mjs";
import { BATCH_SIZE, batchDir, batchOf, contentDir, validateAll } from "./validate.mjs";

const { reels, errors } = validateAll(parse);
const counts = {};
for (const r of reels) counts[r.series] = (counts[r.series] ?? 0) + 1;
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|");
const batches = [...new Set(reels.map((r) => batchOf(r.id)))].sort((a, b) => a - b);

const lines = [
  "# Every reel, in posting order",
  "",
  `Scripts live in batch folders of ${BATCH_SIZE}: \`batch-01\` = vid-1 to vid-${BATCH_SIZE}, \`batch-02\` = the next ${BATCH_SIZE}, and so on.`,
  "`npm run daily` renders them in this order (2 a day by default). Generated by `video/tools/index.mjs`; don't edit by hand.",
  "",
  `${reels.length} reels in ${batches.length} batches: ` + Object.entries(counts).map(([s, n]) => `${s} ${n}`).join(", ") + ".",
  "",
  "| Batch | Reels | Count |",
  "| --- | --- | --- |",
  ...batches.map((b) => {
    const inB = reels.filter((r) => batchOf(r.id) === b);
    const dir = batchDir(inB[0].id);
    return `| [${dir}](#${dir}) | ${inB[0].id} to ${inB[inB.length - 1].id} | ${inB.length} |`;
  }),
];
for (const b of batches) {
  const inB = reels.filter((r) => batchOf(r.id) === b);
  const dir = batchDir(inB[0].id);
  lines.push(
    "",
    `## ${dir}`,
    "",
    "| # | Series | Topic | Title | Length |",
    "| --- | --- | --- | --- | --- |",
    ...inB.map((r) => `| [${r.id}](${dir}/${r.id}.md) | ${r.series} | ${esc(r.topic)} | ${esc(r.title)} | ${r.duration}s |`),
  );
}
if (errors.length) lines.push("", `${errors.length} script(s) currently fail the checker and are not listed.`);
fs.writeFileSync(path.join(contentDir, "INDEX.md"), lines.join("\n") + "\n");
const errNote = errors.length ? `, ${errors.length} with errors` : "";
console.log(`Wrote how-things-work/INDEX.md (${reels.length} reels in ${batches.length} batches${errNote}).`);
